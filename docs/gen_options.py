"""Generate the option reference for the batch how-to from the settings JSON files.

    python docs/gen_options.py          # rewrite docs/source/how-tos/_options_*.rst
    python docs/gen_options.py --check  # exit 1 if the generated files are stale (used by the test suite)

The JSON files in src/rcv_cruncher are the single source of truth for option names, types,
defaults, and descriptions. batch.py reads type/default; the web UI and these docs read the rest.
`placeholder`, `required`, `wide` and `web_default` are read by the web UI only. `wide` is a
layout hint (full-width field); `web_default` is the value the web form starts with when it
differs from the CLI default (the form always writes values explicitly, so the CLI sees them).
Neither is shown in the docs.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "rcv_cruncher"
OUT = ROOT / "docs" / "source" / "how-tos"

HEADER = ".. Generated by docs/gen_options.py from src/rcv_cruncher/{src}. Do not edit by hand.\n\n"


def fmt_default(spec):
    d = spec["default"]
    if d == "":
        return "empty"
    if d in ("None", "np.nan"):
        return "none"
    return str(d).upper() if isinstance(d, bool) else str(d)


def render(settings, src, with_type):
    out = HEADER.format(src=src)
    groups = {}
    for name, spec in settings.items():
        groups.setdefault(spec.get("group", "Other"), []).append((name, spec))
    for group, items in groups.items():
        out += f"{group}\n{'-' * len(group)}\n\n"
        for name, spec in items:
            bits = []
            if with_type:
                bits.append(spec["type"])
            if spec.get("required"):
                bits.append("required")
            bits.append(f"default {fmt_default(spec)}")
            if "applies_when" in spec:
                (field, values), = spec["applies_when"].items()
                bits.append(f"only when ``{field}`` is {', '.join(str(v).upper() if isinstance(v, bool) else str(v) for v in values)}")
            if spec.get("deprecated"):
                bits.append("deprecated")
            out += f"* ``{name}`` ({'; '.join(bits)}): {spec['description']}\n"
        out += "\n"
    return out


def main(check=False):
    stale = []
    for src, fname, with_type in (
        ("contest_set_settings.json", "_options_contest_set.rst", True),
        ("run_config_settings.json", "_options_run_config.rst", False),
    ):
        text = render(json.loads((PKG / src).read_text()), src, with_type)
        target = OUT / fname
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text)
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print("stale generated docs, run `python docs/gen_options.py`:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
